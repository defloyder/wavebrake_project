// Generates lib/core/theme/flag_palettes.dart: every flag of the
// country_flags library rendered and measured — its colours and the share
// of the flag each covers. Not part of the normal test run.
//
//   flutter test test_screens/flag_palettes_test.dart
import 'dart:io';
import 'dart:math' as math;
import 'dart:ui' as ui;

import 'package:country_flags/country_flags.dart';
import 'package:flutter/material.dart';
import 'package:flutter/rendering.dart';
import 'package:flutter_test/flutter_test.dart';

const _w = 90.0, _h = 60.0;

void main() {
  testWidgets('flag palettes', (tester) async {
    final codes = <String>[
      for (var a = 65; a <= 90; a++)
        for (var b = 65; b <= 90; b++)
          if (FlagCode.fromCountryCode(String.fromCharCodes([a, b])) != null)
            String.fromCharCodes([a, b]),
    ];
    final out = StringBuffer()
      ..writeln('// GENERATED by test_screens/flag_palettes_test.dart from the')
      ..writeln('// country_flags library: each flag\'s colours, largest share')
      ..writeln('// first, as 0xAARRGGBB and the share of the flag (0..1).')
      ..writeln('// ignore_for_file: lines_longer_than_80_chars')
      ..writeln()
      ..writeln('const flagPalettes = <String, List<(int, double)>>{');
    for (final code in codes) {
      final key = GlobalKey();
      await tester.pumpWidget(Directionality(
        textDirection: TextDirection.ltr,
        child: Center(
          child: RepaintBoundary(
            key: key,
            child: SizedBox(
              width: _w,
              height: _h,
              child: CountryFlag.fromCountryCode(code,
                  theme: const ImageTheme(width: _w, height: _h)),
            ),
          ),
        ),
      ));
      // The flag loads its picture asynchronously.
      for (var i = 0; i < 10; i++) {
        await tester.runAsync(() => Future<void>.delayed(const Duration(milliseconds: 20)));
        await tester.pump();
      }
      final palette = await tester.runAsync(() async {
        final boundary =
            key.currentContext!.findRenderObject()! as RenderRepaintBoundary;
        final image = await boundary.toImage();
        final data = await image.toByteData(format: ui.ImageByteFormat.rawRgba);
        image.dispose();
        return _palette(data!.buffer.asUint8List());
      });
      if (palette == null || palette.isEmpty) continue;
      out.writeln("  '$code': [${palette.map((p) => '(0x${p.$1.toRadixString(16).padLeft(8, '0').toUpperCase()}, ${p.$2.toStringAsFixed(2)})').join(', ')}],");
    }
    out.writeln('};');
    File('lib/core/theme/flag_palettes.dart').writeAsStringSync(out.toString());
  });
}

/// Colours covering at least 4 % of the flag, near shades merged,
/// largest first (at most 5).
List<(int, double)>? _palette(List<int> rgba) {
  final buckets = <int, List<int>>{}; // key -> [count, r, g, b]
  var total = 0;
  for (var i = 0; i + 3 < rgba.length; i += 4) {
    if (rgba[i + 3] < 200) continue;
    final r = rgba[i], g = rgba[i + 1], b = rgba[i + 2];
    final key = (r >> 4) << 8 | (g >> 4) << 4 | (b >> 4);
    final e = buckets.putIfAbsent(key, () => [0, 0, 0, 0]);
    e[0]++;
    e[1] += r;
    e[2] += g;
    e[3] += b;
    total++;
  }
  if (total == 0) return null;
  final sorted = buckets.values.toList()..sort((a, b) => b[0] - a[0]);
  final merged = <List<double>>[]; // [count, r, g, b] (means)
  for (final e in sorted) {
    final r = e[1] / e[0], g = e[2] / e[0], b = e[3] / e[0];
    final near = merged.where((m) =>
        math.sqrt(math.pow(m[1] - r, 2) + math.pow(m[2] - g, 2) + math.pow(m[3] - b, 2)) < 48);
    if (near.isNotEmpty) {
      near.first[0] += e[0];
      continue;
    }
    merged.add([e[0].toDouble(), r, g, b]);
  }
  merged.sort((a, b) => b[0].compareTo(a[0]));
  return [
    for (final m in merged.take(5))
      if (m[0] / total >= 0.04)
        (0xFF000000 | m[1].round() << 16 | m[2].round() << 8 | m[3].round(),
            m[0] / total),
  ];
}
