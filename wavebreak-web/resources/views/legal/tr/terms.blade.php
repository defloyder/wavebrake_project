                <p class="legal-meta">Son güncelleme: 29 Eylül 2026</p>
                <p>Bu Kullanım Koşulları (“Koşullar”), sizinle WAVEBREAK Platformu’nun sahibi olan gerçek kişi girişimci (“WAVEBREAK”, “biz”) arasındaki sözleşmenin hükümlerini düzenler. Lütfen dikkatle okuyun.</p>

                <section id="definitions">
                    <h2>1. Tanımlar</h2>
                    <ul>
                        <li><strong>Platform (WAVEBREAK)</strong> — bireysel kullanıcılar, ekipler ve işletmeler için güvenli ağ bağlantısı ve erişim yönetimi platformu: wavebreak.com.tr sitesi, WAVEBREAK uygulamaları ve sunucu altyapımız.</li>
                        <li><strong>Kullanıcı</strong>, <strong>siz</strong> — Hesap oluşturan veya Uygulamayı kullanan kişi.</li>
                        <li><strong>Hesap</strong> — Platform’daki kullanıcı hesabınız.</li>
                        <li><strong>Uygulama</strong> — Windows, Android veya iOS için WAVEBREAK uygulaması.</li>
                        <li><strong>Plan</strong> — erişim koşulları: fiyat, süre, cihaz sayısı, trafik miktarı ve eşzamanlı bağlantı sayısı.</li>
                        <li><strong>Abonelik</strong> — seçtiğiniz Plan koşullarında, ödenen süre boyunca altyapımızı kullanma hakkı.</li>
                        <li><strong>Üçüncü taraf profili</strong> — başka bir sağlayıcının hizmetine ait, Uygulamaya kendiniz eklediğiniz bağlantı ayarları.</li>
                    </ul>
                </section>

                <section id="acceptance">
                    <h2>2. Sözleşmenin kurulması</h2>
                    <p>2.1. Hesap oluşturmanız, Abonelik başlatmanız veya bir Plan için ödeme yapmanız ile bu Koşulları kabul etmiş ve bizimle bu Koşullar çerçevesinde bir sözleşme kurmuş olursunuz.</p>
                    <p>2.2. Ücretli bir Abonelik satın alınmadan önce, 6502 sayılı Tüketicinin Korunması Hakkında Kanun ve Mesafeli Sözleşmeler Yönetmeliği uyarınca ön bilgilendirme ve mesafeli sözleşme metinleri Uygulamada size sunulur.</p>
                    <p>2.3. Koşulları kabul etmiyorsanız Platform’u kullanmayın.</p>
                    <p>2.4. Şirketler bizimle ayrı bir yazılı sözleşme yapabilir. Bu durumda o sözleşme bu Koşullardan önce gelir.</p>
                </section>

                <section id="subject">
                    <h2>3. Hizmetin konusu</h2>
                    <p>3.1. Size Platform’a erişim sağlarız:</p>
                    <ul>
                        <li>Planınız kapsamında sunucu altyapımıza güvenli (şifreli) ağ bağlantısı;</li>
                        <li>erişim yönetimi: Hesabınızda cihazların, bağlantı profillerinin ve Abonelik süresinin takibi;</li>
                        <li>Üçüncü taraf profillerini kullanma imkânı da dahil olmak üzere Uygulama.</li>
                    </ul>
                    <p>3.2. Kullanılabilir konumlar, protokoller ve bağlantı türleri Uygulamada gösterilir. Platform’un çalışması ve güvenliği için bunları değiştirebiliriz.</p>
                    <p>3.3. Üçüncü taraf profilleri başka sağlayıcılar tarafından sunulur. Bunlar için hizmet vermeyiz; işleyişlerinden, koşullarından ve içeriklerinden sorumlu değiliz. Üçüncü taraf profillerini kullanmak için WAVEBREAK Aboneliği gerekmez.</p>
                </section>

                <section id="account">
                    <h2>4. Hesap</h2>
                    <p>4.1. Kayıt için geçerli bir e-posta adresi ve şifre gerekir. Gerçek bir e-posta adresi vermeyi ve bu adrese erişiminizi korumayı kabul edersiniz.</p>
                    <p>4.2. Şifrenizin güvenliğinden ve Hesabınız üzerinden yapılan işlemlerden siz sorumlusunuz. Yetkisiz erişimden şüphelenirseniz derhal destek ekibine bildirin.</p>
                    <p>4.3. Hesap kişiseldir. Planınızın cihaz limitini aşacak şekilde başkalarına erişim veremezsiniz. Ekip erişimi uygun bir Plan veya ayrı bir sözleşme ile sağlanır.</p>
                </section>

                <section id="payment">
                    <h2>5. Planlar ve ödeme</h2>
                    <p>5.1. Güncel Planlar <a href="/tr/pricing">Planlar</a> sayfasında ve Uygulamada yayımlanır. Ödeme sırasında aksi belirtilmedikçe fiyatlar Rus rublesi cinsindendir; ödenecek toplam tutar, vergiler dahil olarak, ödemeden önce gösterilir.</p>
                    <p>5.2. Abonelik, Planın süresi boyunca — bir ay veya bir yıl — geçerlidir. Yıllık Plan tüm yıl için peşin ödenir.</p>
                    <p>5.3. Ödemeler Uygulamada belirtilen ödeme kuruluşu aracılığıyla alınır. Ödeme, ödeme kuruluşundan onay alındığında tamamlanmış sayılır.</p>
                    <p>5.4. Otomatik yenileme sunulursa, bu durum yenileme fiyatı ve süresiyle birlikte ödemeden önce açıkça gösterilir. Otomatik yenilemeyi Uygulamadan veya destek ekibine yazarak dilediğiniz zaman kapatabilirsiniz; bir sonraki ödemeden önce durdurulur.</p>
                    <p>5.5. Plan fiyatlarını değiştirebiliriz. Değişiklik, ödemesi yapılmış süreyi etkilemez.</p>
                    <p>5.6. Ödemeler başlatılana kadar erişim test modunda ücretsiz sağlanabilir. Test modunda erişimi dilediğimiz zaman değiştirebilir veya sona erdirebiliriz.</p>
